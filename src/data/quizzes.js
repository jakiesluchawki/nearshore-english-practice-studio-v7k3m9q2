export function getLessonQuiz(lesson) {
  const [rawAnswer, intention] = quizBlueprints[lesson.id] || [lesson.phrases[0], lesson.goal];
  const answer = completeRecruiterPhrase(rawAnswer);
  const alternatives = [...new Set(lesson.phrases.filter((phrase) => phrase && phrase !== answer))].slice(0, 2);
  const choices = [answer, ...alternatives].filter(Boolean);
  const shift = lesson.id % choices.length;
  const options = [...choices.slice(shift), ...choices.slice(0, shift)];
  const acceptedAnswers = [...new Set([answer, ...(equallyNaturalAnswers[lesson.id] || [])])]
    .filter((phrase) => options.includes(phrase));

  return { answer, acceptedAnswers, intention, options, context: "same-lesson" };
}
